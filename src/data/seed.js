export function createSeedEvents(now = new Date()) {
  return templates.map(
    (
      [id, title, clubId, category, offset, time, location, capacity, summary, description, bring],
      i,
    ) => {
      const day = new Date(now.getFullYear(), now.getMonth(), now.getDate() + offset);
      return {
        id,
        title,
        clubId,
        category,
        date: localDate(day),
        time,
        location,
        capacity,
        summary,
        description,
        bring,
        creatorId: i % 2 ? 'demo-2' : 'demo-1',
      };
    },
  );
}
